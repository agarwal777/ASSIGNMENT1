"""Generate db/seed_network.sql from seed/network.csv (synthetic contacts).

The SQL replaces the demo template (schema `demo`, not reachable from the app) and clears
existing visitors' synthetic copies so each visitor is re-seeded with the new network on next
visit. Run it once in the Supabase SQL Editor. Contact ids are deterministic (uuid5).

Usage (from finn/):  workers/.venv/Scripts/python workers/gen_network_sql.py
"""
from __future__ import annotations

import csv
import uuid
from pathlib import Path

NS = uuid.UUID("6f1c2d3e-0000-4000-8000-00000000f1aa")  # fixed namespace → stable ids


def q(v: str | None) -> str:
    if v is None or v == "":
        return "null"
    return "'" + v.replace("'", "''") + "'"


def main() -> None:
    rows = list(csv.DictReader(Path("seed/network.csv").open(encoding="utf-8")))
    contacts: dict[str, dict] = {}
    for r in rows:
        contacts.setdefault(r["contact_id"], r)

    out = ["-- Generated by workers/gen_network_sql.py from seed/network.csv. Synthetic people only.",
           "begin;",
           "delete from demo.contact_stints;",
           "delete from demo.contacts;",
           "-- Visitors re-seed on their next visit (seed_demo_user copies only when they have none).",
           "delete from public.contacts where is_synthetic;"]
    for cid, r in contacts.items():
        tags = "{" + ",".join('"' + t.strip().replace('"', "") + '"' for t in r["tags"].split(";") if t.strip()) + "}"
        out.append(
            "insert into demo.contacts (id, display_name, closeness, last_contacted, tags, is_synthetic) "
            f"values ('{uuid.uuid5(NS, cid)}', {q(r['display_name'])}, {int(r['closeness'])}, "
            f"{q(r['last_contacted'])}, '{tags}', true);")
    for r in rows:
        known = "true" if r["start"] else "false"
        out.append(
            "insert into demo.contact_stints (contact_id, org_canonical, role, function, start_date, end_date, dates_known) "
            f"values ('{uuid.uuid5(NS, r['contact_id'])}', {q(r['org'])}, {q(r['role'])}, {q(r['function'])}, "
            f"{q(r['start'])}, {q(r['end'])}, {known});")
    out.append("commit;")
    Path("db/seed_network.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote db/seed_network.sql: {len(contacts)} contacts, {len(rows)} stints")


if __name__ == "__main__":
    main()
